/**
 * Wave-8 W5 — three-layer readiness model. The daemon "device" is the
 * execution surface; readiness collapses heartbeat freshness into one of:
 *   connected — heartbeat within ONLINE_WINDOW_MS (90s)
 *   stale     — heartbeat older than 90s but device row exists
 *   offline   — no heartbeat recorded yet
 */
export type RuntimeDaemonStatus = 'connected' | 'stale' | 'offline';

