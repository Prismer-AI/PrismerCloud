    @staticmethod
    def _format_manifest(entries: List[Dict[str, Any]]) -> str:
        """Format a manifest into the ``- path [title] — description`` block.

        Mirrors the TS-side ``formatManifest`` in
        ``daemon/memory/fork/select-memories.ts``. Both copies must
        produce identical output so the selector LLM sees a stable shape
        regardless of which host orchestrated it.
        """
        out: List[str] = []
        for e in entries[:MAX_MANIFEST_ENTRIES]:
            path = e.get("path") or ""
            if not path:
                continue
            title = e.get("title")
            desc = e.get("description") or "(no description)"
            if isinstance(desc, str) and len(desc) > 200:
                desc = desc[:199] + "…"
            title_part = f" [{title[:79] + '…' if isinstance(title, str) and len(title) > 80 else title}]" if title else ""
            out.append(f"- {path}{title_part} — {desc}")
        return "\n".join(out)

    @staticmethod
    def _parse_selector_output(raw_text: str, entries: List[Dict[str, Any]]) -> List[str]:
        """Parse JSON from the LLM, validate paths against the manifest.

        Mirrors the TS ``parseSelectorOutput`` — tolerates ```json fences,
        drops hallucinated paths, dedups, caps at MAX_SELECTED. Returns
        an empty list on any parse failure (never throws).
        """
        text = raw_text.strip()
        if not text:
            return []
        # Strip optional code-fence wrapper.
        if text.startswith("```"):
            text = text.lstrip("`")
            if text.lower().startswith("json"):
                text = text[4:]
            text = text.strip()
            if text.endswith("```"):
                text = text[:-3].strip()
        try:
            parsed = json.loads(text)
        except Exception:
            return []
        if not isinstance(parsed, dict):
            return []
        names = parsed.get("selected_memories")
        if not isinstance(names, list):
            return []
        valid_paths = {e.get("path") for e in entries if isinstance(e.get("path"), str)}
        out: List[str] = []
        for n in names:
            if not isinstance(n, str):
                continue
            if n not in valid_paths:
                continue
            if n in out:
                continue
            out.append(n)
            if len(out) >= MAX_SELECTED:
                break
        return out

    def _tool_memory_recall(self, args: Dict[str, Any]) -> str:
        """Handle a ``memory_recall`` tool call.

        Drives the 3-stage flow: manifest → fork_query → finalize. Empty
        result is a normal outcome — the selector is told to be selective
        and we never want to pretend recall succeeded when it didn't.
        Emits one ``recall_pull`` per finalized entry so the trace tab
        reflects fork-driven recalls just like agent-driven ones.
        """
        query = args.get("query") or ""
        if not isinstance(query, str) or not query.strip():
            return json.dumps({"error": "missing_query", "message": "memory_recall requires `query`"})
        recent_tools_raw = args.get("recentTools") if isinstance(args, dict) else None
        recent_tools: List[str] = []
        if isinstance(recent_tools_raw, list):
            recent_tools = [t for t in recent_tools_raw if isinstance(t, str)]

        # Stage 1 — manifest from daemon.
        entries = self._fetch_manifest(query)
        if not entries:
            return json.dumps({"query": query, "results": []})

        # Stage 2 — host LLM selector. fork_query() returns "" on no-key
        # or transport error; treat as "selector chose nothing".
        manifest_text = self._format_manifest(entries)
        tools_section = (
            f"\n\nRecently used tools: {', '.join(recent_tools)}" if recent_tools else ""
        )
        user_msg = f"Query: {query}\n\nAvailable memories:\n{manifest_text}{tools_section}"
        raw = self.fork_query(SELECT_MEMORIES_SYSTEM_PROMPT, user_msg, max_tokens=256)
        selected_paths = self._parse_selector_output(raw, entries)
        if not selected_paths:
            return json.dumps({"query": query, "results": []})

        # Stage 3 — daemon resolves selected paths to RelevantMemory[].
        results = self._finalize_recall(selected_paths)
        # Per-result observability so the trace tab attributes recall_pull
        # to the correct page even when fork drove the selection.
        for r in results:
            self._emit_observability(
                event_type="recall_pull",
                page_id=r.get("pageId"),
                query=query,
                metrics={"tokenCount": _estimate_tokens(r.get("snippet") or "")},
                metadata={
                    "sessionId": self._session_id,
                    "turnIndex": self._turn_index,
                    "tool": "memory_recall",
                    "forkLabel": "memory_recall",
                },
            )
        return json.dumps({"query": query, "results": results})

    def _tool_memory_load(self, args: Dict[str, Any]) -> str:
        uri = args.get("uri")
        ws = args.get("workspaceId")
        path = args.get("path")
        loaded = self._load_page(uri=uri, workspace_id=ws, path=path)
        if loaded is None:
            return json.dumps({"error": "not_found", "message": "memory_load: page not found"})
        page = loaded.get("page") or {}
        # Emit recall_pull. Page id from the response so we attribute to
        # the canonical id even when the caller passed a path.
        self._emit_observability(
            event_type="recall_pull",
            page_id=page.get("id"),
            query=None,
            metrics={"tokenCount": _estimate_tokens(loaded.get("content") or "")},
            metadata={
                "sessionId": self._session_id,
                "turnIndex": self._turn_index,
                "tool": "memory_load",
                "uri": uri,
                "path": path,
            },
        )
        return json.dumps(loaded)


