def _truncate_to_budget(content: str, *, max_lines: int, max_bytes: int) -> str:
    """Mirrors hooks.ts ``truncateToBudget`` — line cap then byte cap."""
    out = content
    lines = out.split("\n")
    if len(lines) > max_lines:
        out = "\n".join(lines[:max_lines])
    while len(out.encode("utf-8")) > max_bytes and out:
        cut = max(1, int(len(out) * 0.9))
        out = out[:cut]
    return out


def _estimate_tokens(s: str) -> int:
    """Rough char-to-token estimate matching hooks.ts ``estimateTokens``."""
    return -(-len(s) // 4)  # ceil(len/4)


