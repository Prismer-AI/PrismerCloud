"""Hermes memory provider backed by the Prismer daemon.

Bridges Hermes agent sessions to Prismer's daemon-side memory subsystem
(Line C). Implements the Hermes `MemoryProvider` ABC so an end user with
``memory.provider = prismer-daemon`` in their config gets:

  - ``INDEX.md`` injected into the system prompt at session start
    (via ``system_prompt_block()`` — preloaded once in ``initialize``)
  - **opt-in** workspace recall via ``prefetch(query)``. By default the
    provider treats this as a no-op (returns empty string) — agents call
    ``memory_search`` selectively when they actually need prior memory
    instead of paying the auto-injection tax on every turn. Set
    ``PRISMER_MEMORY_AUTO_PREFETCH=1`` to restore the legacy behavior
    (hybrid search + ``<memory-context>`` fence + ``recall_inject`` events).
    See doc 25 §3 支柱 1 (M-A) for the rationale.
  - ``memory_search`` + ``memory_load`` tools exposed to the model
    (``get_tool_schemas()``), backed by daemon RPC and emitting
    ``recall_pull`` events on each call
  - graceful no-op fallbacks when the daemon is offline (no exception
    bubbles into Hermes' main loop — that would kill the agent)

What this provider does NOT do (v0 scope):
  - ``queue_prefetch``: no background prefetch optimization yet
  - ``sync_turn``: no per-turn writes (aggressive; doc 19 I6 owns
    consolidation via the 4-stage subagent flow)
  - ``on_session_end``: no end-of-session reflection write
  - any cloud-side calls — the provider only talks to ``127.0.0.1:3210``;
    the daemon's outbox worker is responsible for cloud upload (C2)

Configuration (env-based, matches Prismer SDK pattern):

  PRISMER_DAEMON_URL    default ``http://127.0.0.1:3210``
  PRISMER_WORKSPACE_ID  required for the provider to be ``available``
  PRISMER_AGENT_IM_USER_ID  optional; used as ``actorImUserId`` on
                             observability events. Falls back to
                             ``"hermes-agent"``.
  PRISMER_MEMORY_AUTO_PREFETCH  optional; ``1``/``true`` re-enables the
                             pre-M-A auto-injection behavior in
                             ``prefetch()``. Default off — agents are
                             expected to call ``memory_search`` only
                             when prior memory genuinely helps.

Wire format: see ``daemon/memory/envelope.ts`` for the locked
``MemoryOutboxEnvelope`` zod union. Observability events POST to
``/local/memory/observability/emit``; the daemon validates the envelope
on the way in and dead-letters bad payloads on its side, so the provider
can fire-and-forget.
"""

