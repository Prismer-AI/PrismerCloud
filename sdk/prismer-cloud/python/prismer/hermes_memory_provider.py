    def _make_client(self) -> Optional["httpx.Client"]:
        if not _HTTPX_AVAILABLE:
            return None
        # Default timeout is overridden per-call. Persistent client reuses
        # the TCP connection across calls (matters for high-frequency
        # observability emissions).
        return httpx.Client(timeout=_LOAD_TIMEOUT)

    def _get_client(self) -> Optional["httpx.Client"]:
        with self._client_lock:
            if self._client is None and _HTTPX_AVAILABLE:
                self._client = self._make_client()
            return self._client

    def _preload_index(self) -> str:
        """Fetch INDEX.md content via daemon RPC, cap at 200 lines / 25 KB.

        Returns "" when the page doesn't exist (404), the daemon errors,
        or content is empty.
        """
        client = self._get_client()
        if client is None:
            return ""
        uri = f"prismer://workspace/{self._workspace_id}/memory/INDEX.md"
        try:
            r = client.get(
                f"{self._daemon_url}/local/memory/load",
                params={"uri": uri},
                timeout=_LOAD_TIMEOUT,
            )
        except Exception as e:
            logger.warning("[PrismerDaemonMemory] INDEX.md preload network error: %s", e)
            return ""
        if r.status_code == 404:
            logger.debug("[PrismerDaemonMemory] no INDEX.md in workspace %s", self._workspace_id)
            return ""
        if r.status_code != 200:
            logger.warning(
                "[PrismerDaemonMemory] INDEX.md load returned HTTP %d", r.status_code,
            )
            return ""
        try:
            body = r.json()
        except Exception as e:
            logger.warning("[PrismerDaemonMemory] INDEX.md JSON decode failed: %s", e)
            return ""
        content = body.get("content")
        if not content or not isinstance(content, str):
            return ""
        return _truncate_to_budget(content, max_lines=_INDEX_MAX_LINES, max_bytes=_INDEX_MAX_BYTES)

    def _search(
        self,
        query: str,
        *,
        top_k: int = _AUTO_INJECT_TOP_K,
        max_bytes: int = _DEFAULT_MAX_BYTES,
        page_type: Optional[str] = None,
    ) -> List[Dict[str, Any]]:
        """Call ``GET /local/memory/search`` and return parsed results.

        Returns ``[]`` on any failure — never raises.

        ``page_type`` mirrors the canonical TS adapter's single-value
        ``pageType`` query param (see
        ``sdk/prismer-cloud/runtime/src/adapters/memory-tools.ts`` —
        daemon's ``/local/memory/search`` accepts one ``pageType`` per
        request; multi-value support is post-MVP). Pass ``None`` to omit
        the filter entirely.
        """
        client = self._get_client()
        if client is None:
            return []
        params: Dict[str, Any] = {
            "workspaceId": self._workspace_id,
            "q": query,
            "topK": top_k,
            "maxBytes": max_bytes,
        }
        if page_type:
            params["pageType"] = page_type
        try:
            r = client.get(
                f"{self._daemon_url}/local/memory/search",
                params=params,
                timeout=_SEARCH_TIMEOUT,
            )
        except Exception as e:
            logger.warning("[PrismerDaemonMemory] memory_search network error: %s", e)
            return []
        if r.status_code != 200:
            logger.warning("[PrismerDaemonMemory] memory_search HTTP %d", r.status_code)
            return []
        try:
            body = r.json()
        except Exception:
            return []
        results = body.get("results")
        if not isinstance(results, list):
            return []
        return results

