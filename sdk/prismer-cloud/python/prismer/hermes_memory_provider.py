def _parse_extract_output(raw_text: str) -> List[Dict[str, Any]]:
    """Mirror of TS-side parseExtractOutput. Returns 0..3 valid proposals."""
    text = raw_text.strip()
    if not text:
        return []
    if text.startswith("```"):
        text = text.lstrip("`")
        if text.lower().startswith("json"):
            text = text[4:]
        text = text.strip()
        if text.endswith("```"):
            text = text[:-3].strip()
    try:
        parsed = json.loads(text)
    except Exception:
        return []
    if not isinstance(parsed, dict):
        return []
    arr = parsed.get("proposals")
    if not isinstance(arr, list):
        return []
    out: List[Dict[str, Any]] = []
    for entry in arr:
        if not isinstance(entry, dict):
            continue
        path = entry.get("path")
        title = entry.get("title")
        summary = entry.get("summary")
        rationale = entry.get("rationale", "")
        confidence = entry.get("confidence", 0.5)
        if not isinstance(path, str) or not path.startswith("memory/"):
            continue
        if not isinstance(title, str) or not title.strip():
            continue
        if not isinstance(summary, str) or not summary.strip():
            continue
        if not isinstance(rationale, str):
            rationale = ""
        if not isinstance(confidence, (int, float)):
            confidence = 0.5
        confidence = max(0.0, min(1.0, float(confidence)))
        out.append(
            {
                "path": path,
                "title": title[:80],
                "summary": summary[:4000],
                "rationale": rationale[:500],
                "confidence": confidence,
            }
        )
        if len(out) >= 3:
            break
    return out


