class PrismerDaemonMemoryProvider(MemoryProvider):
    """Hermes memory provider that bridges to the Prismer daemon.

    All daemon RPC calls are sync httpx; Hermes' provider methods are
    sync, so the sync client matches. On failure, methods log a warning
    and return safe defaults — never raise into Hermes' main loop.

    A single provider instance services one workspace per process. The
    workspace id is read from ``PRISMER_WORKSPACE_ID`` at construction.
    Multi-workspace support is post-MVP.
    """

    def __init__(self) -> None:
        self._daemon_url = os.environ.get("PRISMER_DAEMON_URL", DEFAULT_DAEMON_URL).rstrip("/")
        self._workspace_id = os.environ.get("PRISMER_WORKSPACE_ID", "")
        self._actor_im_user_id = os.environ.get("PRISMER_AGENT_IM_USER_ID", "hermes-agent")
        self._device_id = os.environ.get("PRISMER_DAEMON_ID", "hermes-provider")

        # Cached state
        self._session_id: str = ""
        self._turn_index: int = 0
        self._index_content: str = ""
        self._client: Optional["httpx.Client"] = None
        self._client_lock = threading.Lock()

    # -- Identity & availability --------------------------------------------

    @property
    def name(self) -> str:
        return "prismer-daemon"

    def is_available(self) -> bool:
        """Return True iff env is wired AND the daemon answers /healthz fast.

        The fast-fail probe (200ms timeout) is intentional — Hermes calls
        this during startup to decide whether to activate the provider; a
        long network stall would block agent boot.

        The probe routes through ``self._make_client()`` so that injected
        transports (test fixtures, prod proxy / CA bundle / mTLS) apply
        uniformly across the provider's lifecycle. The client is still
        ephemeral (closed after the probe) — only ``initialize()`` retains
        the persistent client.
        """
        if not _HTTPX_AVAILABLE:
            logger.debug("[PrismerDaemonMemory] httpx not importable — provider unavailable")
            return False
        if not self._workspace_id:
            logger.debug("[PrismerDaemonMemory] PRISMER_WORKSPACE_ID unset — provider unavailable")
            return False
        client = self._make_client()
        if client is None:
            return False
        try:
            with client as c:
                r = c.get(f"{self._daemon_url}/healthz", timeout=_HEALTH_TIMEOUT)
                return r.status_code == 200
        except Exception as e:
            logger.debug("[PrismerDaemonMemory] /healthz probe failed: %s", e)
            return False

    # -- Lifecycle ----------------------------------------------------------

    def initialize(self, session_id: str, **kwargs: Any) -> None:
        """Cache session metadata and preload INDEX.md.

        Called once at agent startup. Failure to fetch INDEX.md is
        non-fatal — provider continues with empty system_prompt_block.
        """
        self._session_id = session_id
        # Allow runtime override from kwargs if Hermes layer sets it.
        kw_actor = kwargs.get("agent_im_user_id") or kwargs.get("agent_identity")
        if kw_actor:
            self._actor_im_user_id = str(kw_actor)
        self._client = self._make_client()
        self._index_content = self._preload_index()

    def shutdown(self) -> None:
        """Close the persistent HTTP client. Safe to call multiple times."""
        with self._client_lock:
            if self._client is not None:
                try:
                    self._client.close()
                except Exception as e:  # pragma: no cover — defensive
                    logger.debug("[PrismerDaemonMemory] client close failed: %s", e)
                self._client = None

    # -- System prompt block + recall ---------------------------------------

    def system_prompt_block(self) -> str:
        """Return INDEX.md + memory-curation skill, both wrapped in headings.

        Two parts, joined with a blank line:

        1. ``## Workspace memory (INDEX)`` — the cached INDEX.md content,
           omitted when load failed (Hermes skips empty blocks anyway).
        2. ``## Memory curation skill`` — the asset-driven memory-page
           guidance from doc 27 §3. Always emitted because the skill text
           is bundled with this module — no daemon dependency.

        Even when INDEX is missing, the skill block alone teaches the
        agent when to write memory pages, so the asset-driven flow works
        on a brand-new workspace with zero existing memory.
        """
        parts: List[str] = []
        if self._index_content:
            parts.append(f"## Workspace memory (INDEX)\n\n{self._index_content}")
        parts.append(f"## Memory curation skill\n\n{MEMORY_CURATION_SKILL_TEXT}")
        return "\n\n".join(parts)

    def prefetch(self, query: str, *, session_id: str = "") -> str:
        """Optionally search workspace memory and return a ``<memory-context>`` fence.

        **Default behavior (M-A, doc 25 §3 支柱 1): no-op.** Returns ""
        without hitting the daemon. Per-turn auto-injection was retired
        because it spammed idle conversation with low-relevance hits,
        polluted the prompt cache key (token cost ↑↑ on long sessions),
        and gave the agent no agency to refuse bad recalls. Agents that
        actually need prior memory call ``memory_search`` selectively
        through the tool surface.

        **Legacy behavior** is preserved behind ``PRISMER_MEMORY_AUTO_PREFETCH=1``:
        when set, runs hybrid search and emits one ``recall_inject`` event
        per included result. Returns empty string on daemon error or zero
        results — never raises.

        Lifecycle precondition: ``initialize()`` must be called first per
        the Hermes ABC contract. If invoked before ``initialize()`` (no
        cached session id), this method logs a warning and returns ""
        rather than operating with undefined session state.
        """
        if not _auto_prefetch_enabled():
            # Default M-A path: no-op. Don't hit the daemon, don't emit
            # observability, don't allocate a fence. The whole point of
            # this default is zero per-turn cost.
            return ""
        if not self._session_id:
            logger.warning(
                "%s: prefetch() called before initialize() — caller must call initialize() first per Hermes ABC",
                self.name,
            )
            return ""
        if not query or not query.strip():
            return ""
        results = self._search(query, top_k=_AUTO_INJECT_TOP_K, max_bytes=_DEFAULT_MAX_BYTES)
        if not results:
            return ""

        # Build the <memory-context> fence — same shape as phase-1 hooks.ts
        # buildFence() so cloud + adapter-side unit tests can use the same
        # fixtures.
        body = "\n\n".join(
            f"## {r.get('path', '<unknown>')}\n{r.get('snippet', '')}"
            for r in results
        )
        fence = f"<memory-context>\n{body}\n</memory-context>"

        # Fire one recall_inject event per result. Failures here are
        # logged-only — the recall content already went into the prompt;
        # missing observability shouldn't break the agent turn.
        for r in results:
            self._emit_observability(
                event_type="recall_inject",
                page_id=r.get("pageId"),
                query=query,
                metrics={
                    "tokenCount": r.get("tokenCount", 0),
                    "relevanceScore": r.get("score", 0.0),
                    "topK": len(results),
                },
                metadata={
                    "sessionId": session_id or self._session_id,
                    "turnIndex": self._turn_index,
                },
            )

        return fence

    def queue_prefetch(self, query: str, *, session_id: str = "") -> None:
        """No-op for v0.

        Hermes' background-prefetch optimization (queue_prefetch fires
        after a turn so the next turn's prefetch() returns cached results
        without blocking) is post-MVP per doc 23 §10. The daemon's hybrid
        search is fast enough on local SQLite that synchronous prefetch
        is acceptable — we revisit if benchmarks show p95 latency issues.
        """

    def sync_turn(self, user_content: str, assistant_content: str, *, session_id: str = "") -> None:
        """No-op for v0.

        Per-turn writes back to workspace memory are aggressive — every
        turn would flood ``im_memory_files`` with raw conversation
        chunks. v0 ships only the read path. Real consolidation
        (deduped, distilled facts) is doc 19 I6's 4-stage subagent flow,
        dispatched separately. We track turn index for observability
        attribution but emit nothing here.
        """
        self._turn_index += 1

    def on_session_end(self, messages: List[Dict[str, Any]]) -> None:
        """M-C session-end fork extract (doc 25 §3 支柱 3).

        Walks the session transcript, asks the host LLM via
        ``fork_query`` to propose 0–3 short memory updates, and emits
        each accepted proposal to the daemon outbox as a
        ``memory.proposal`` envelope event. The daemon's outbox worker
        carries them to the cloud's ``/memory/sync/inbox``, which routes
        them into ``im_memory_proposals`` for the user to review in the
        Library Memory view.

        Failure modes return early without raising:
          - empty transcript
          - daemon RPC client unavailable
          - fork_query returns "" (no API key, network error)
          - selector LLM returned malformed JSON

        The agent-actor JWT problem (per outbox-worker.ts header note):
        these proposals carry ``actorImUserId = self._actor_im_user_id``,
        which Line A's sync inbox filters against ``JWT.subject``. The
        daemon's existing CloudClient uses the human-owner token, so
        agent-actor proposals stay in pending status until per-agent
        token issuance ships. That's acceptable for v0 — they're just
        held in the daemon outbox a bit longer.
        """
        if not _HTTPX_AVAILABLE or not messages:
            return
        if not self._session_id or not self._workspace_id:
            return
        # Build a compact transcript. Cap at ~4000 chars to keep the
        # extract LLM call cheap; older messages are discarded.
        transcript = self._compress_transcript(messages, max_chars=4000)
        if not transcript:
            return
        try:
            raw = self.fork_query(_EXTRACT_SYSTEM_PROMPT, transcript, max_tokens=1024)
        except Exception as err:
            logger.warning("[PrismerDaemonMemory] on_session_end fork_query failed: %s", err)
            return
        proposals = _parse_extract_output(raw)
        if not proposals:
            return
        # Emit each proposal as a memory.proposal envelope through the
        # existing /local/memory/observability/emit endpoint (it's a
        # pass-through to slot.outbox.enqueue with envelope schema
        # validation).
        client = self._get_client()
        if client is None:
            return
        for p in proposals:
            event_id = uuid.uuid4().hex[:26].upper()
            created_at = datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")
            envelope: Dict[str, Any] = {
                "eventId": event_id,
                "schemaVersion": 1,
                "eventType": "memory.proposal",
                "workspaceId": self._workspace_id,
                "actorImUserId": self._actor_im_user_id,
                "actorKind": "agent",
                "deviceId": self._device_id,
                "createdAt": created_at,
                "idempotencyKey": f"proposal:{self._session_id}:{p['path']}:{event_id[:8]}",
                "sessionId": self._session_id,
                "pagePath": p["path"],
                "baseVersion": 0,
                "operation": "create",
                "contentDiff": f"# {p['title']}\n\n{p['summary']}",
                "rationale": p.get("rationale", ""),
                "confidence": p["confidence"],
                "sourceRefs": [f"session:{self._session_id}"],
            }
            try:
                client.post(
                    f"{self._daemon_url}/local/memory/observability/emit",
                    json=envelope,
                    timeout=_EMIT_TIMEOUT,
                )
            except Exception as err:
                logger.debug("[PrismerDaemonMemory] proposal emit failed (%s): %s", p["path"], err)

    def _compress_transcript(self, messages: List[Dict[str, Any]], *, max_chars: int) -> str:
        """Render a Hermes message list into a short transcript string.

        Hermes messages are typically ``{ role, content }`` dicts;
        we accept lists of such dicts and project to ``ROLE: content``
        lines, truncating from the FRONT (older messages discarded
        first) to fit the budget. The fork extract LLM only needs
        recent decisions, not the full session.
        """
        lines: List[str] = []
        for m in messages:
            if not isinstance(m, dict):
                continue
            role = str(m.get("role") or "").strip().upper()
            content = m.get("content")
            if isinstance(content, list):
                # Some hosts return [{type:'text', text:'...'}].
                pieces: List[str] = []
                for blk in content:
                    if isinstance(blk, dict) and blk.get("type") == "text":
                        t = blk.get("text")
                        if isinstance(t, str):
                            pieces.append(t)
                content = "\n".join(pieces)
            if not isinstance(content, str):
                continue
            content = content.strip()
            if not content:
                continue
            lines.append(f"{role}: {content}")
        if not lines:
            return ""
        out = "\n".join(lines)
        # Truncate from the front so the most recent turns survive.
        if len(out) > max_chars:
            out = out[-max_chars:]
            # Snap to the nearest line boundary for readability.
            nl = out.find("\n")
            if nl > 0:
                out = out[nl + 1 :]
        return out

