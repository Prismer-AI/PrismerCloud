#!/usr/bin/env node
// Regenerate every foreign-runtime embedded copy of the memory-curation skill
// from the canonical sdk/prismer-cloud/built-in-skills/memory-curation/SKILL.md.
//
// The runtime TS host (sdk/prismer-cloud/runtime/src/skills/memory-curation.ts)
// is NOT a target anymore — it reads the canonical SKILL.md from disk at
// startup via the `runtime/built-in-skills/` tarball mirror populated by
// `runtime/scripts/prebuild-copy-built-in-skills.cjs`. Drift between runtime
// TS and canonical is therefore structurally impossible.
//
// Foreign-runtime targets (3 hosts that cannot share filesystem with the
// runtime npm tarball):
//   1. openclaw TS        → sdk/prismer-cloud/openclaw-channel/src/memory-curation-skill.ts
//                           (used by OpenClaw renderer; @prismer/openclaw-channel
//                           ships its own TS source so each install carries an
//                           embedded copy)
//   2. Python (Hermes)    → sdk/prismer-cloud/python/prismer/_memory_curation_skill.py
//                           (used by hermes_memory_provider.system_prompt_block;
//                           Python package ships independently of the TS runtime)
//   3. Claude Code plugin → sdk/prismer-cloud/claude-code-plugin/skills/memory-curation/SKILL.md
//                           (auto-discovered by CC plugin skill loader; direct
//                           file copy — separate Anthropic marketplace package)
//
// Run from anywhere — paths are resolved relative to this script's location:
//   node sdk/prismer-cloud/runtime/scripts/regenerate-memory-curation-skill.cjs
//
// CI verification (test/skill-memory-curation-sync.test.ts) catches drift if
// you forget to re-run after editing the canonical .md.

const fs = require('node:fs');
const path = require('node:path');

const repoRoot = path.resolve(__dirname, '..', '..', '..', '..');
const canonicalPath = path.join(
  repoRoot,
  'sdk',
  'prismer-cloud',
  'built-in-skills',
  'memory-curation',
  'SKILL.md',
);

const md = fs.readFileSync(canonicalPath, 'utf8');

// Validate that the canonical content is safe to embed via the simple
// "escape backticks only" rule below. We allow backslashes in general (a
// future skill might include regex examples like `\d+`); we only reject
// the two hazards that would actually break the embedded TS template:
//
//   - `\${`  →  would interpolate inside a TS template literal even if
//               the leading `\` were escaped, because `\$` is not a
//               recognized JS string escape and collapses to `$`.
//   - trailing `\` → would escape the closing backtick.
//
// For the Python triple-quoted output: reject any `"""` in the body
// (would close the string early) and any trailing `"` (would merge with
// the closing `"""` and produce an unintended `""""`).
if (md.endsWith('\\')) {
  throw new Error('memory-curation SKILL.md ends with a backslash — would escape the closing backtick in the TS embed');
}
if (md.includes('${')) {
  // Any `${` is hazardous because JS template-literal interpolation depends on
  // the parity of preceding backslashes (`\${` escapes; `\\${` does NOT escape;
  // `\\\${` escapes again; …). Rather than re-implement that parity check,
  // reject any occurrence outright. If a future skill genuinely needs `${`,
  // the author can hand-edit the regen script to apply the right escape.
  throw new Error('memory-curation SKILL.md contains ${ — would interpolate inside the TS template literal');
}
if (md.includes('"""')) {
  throw new Error('memory-curation SKILL.md contains """ — would close the Python triple-quoted string early');
}
if (md.endsWith('"')) {
  throw new Error('memory-curation SKILL.md ends with " — would produce """" in the Python embed');
}

const escapedTs = md.replace(/`/g, '\\`');

const targets = [
  {
    label: 'openclaw TS',
    out: path.join(
      repoRoot,
      'sdk/prismer-cloud/openclaw-channel/src/memory-curation-skill.ts',
    ),
    content: `// SOURCE: sdk/prismer-cloud/built-in-skills/memory-curation/SKILL.md (canonical)
//
// OpenClaw-side embedded copy. @prismer/openclaw-channel ships TypeScript
// source files directly and cannot read the runtime npm tarball mirror,
// so the SKILL.md content is embedded as a TS template literal here.
// Regenerated by sdk/prismer-cloud/runtime/scripts/regenerate-memory-curation-skill.cjs.
// Drift detection: runtime/test/skill-memory-curation-sync.test.ts.

export const MEMORY_CURATION_SKILL_NAME = 'memory-curation';
export const MEMORY_CURATION_SKILL_TEXT = \`${escapedTs}\`;
`,
  },
  {
    label: 'Python (Hermes)',
    out: path.join(repoRoot, 'sdk/prismer-cloud/python/prismer/_memory_curation_skill.py'),
    content: `"""Memory curation skill content (embedded for Hermes).

SOURCE: sdk/prismer-cloud/built-in-skills/memory-curation/SKILL.md (canonical)

The Hermes provider injects this into system_prompt_block at initialize().
This Python module is regenerated by
sdk/prismer-cloud/runtime/scripts/regenerate-memory-curation-skill.cjs so it
stays in lockstep with the canonical SKILL.md.
Drift detection: runtime/test/skill-memory-curation-sync.test.ts.
"""

MEMORY_CURATION_SKILL_NAME = "memory-curation"
MEMORY_CURATION_SKILL_VERSION = 1

MEMORY_CURATION_SKILL_TEXT = """${md}"""
`,
  },
  {
    label: 'Claude Code plugin SKILL.md',
    out: path.join(
      repoRoot,
      'sdk/prismer-cloud/claude-code-plugin/skills/memory-curation/SKILL.md',
    ),
    // Direct file copy — CC plugin's skill discovery reads SKILL.md verbatim
    // (frontmatter + body), so the canonical .md is the file.
    content: md,
    isDirectCopy: true,
  },
];

for (const t of targets) {
  fs.mkdirSync(path.dirname(t.out), { recursive: true });
  fs.writeFileSync(t.out, t.content);
  const rel = path.relative(process.cwd(), t.out);
  console.log(
    `wrote ${rel} (${t.content.length} bytes${t.isDirectCopy ? ', direct copy' : ', wrapped'})`,
  );
}
